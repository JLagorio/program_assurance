# Generate mod-zz-compare-v2.js: python3 -I badata2.py <SP>
# Merges the new pairs (pairs-new.json, plus pairs-v2new.json once it exists), the screenshots on disk (img/),
# the agents' notes (v2/*/notes.json) and the v2 summary (v2sum.json) into window.PA.BA2.
import json, os, sys, glob, re
SP = sys.argv[1]; V = SP + "/vanta"; BA = V + "/v2/ba"
old = open(V + "/proto/mod-zz-compare-data.js").read(); old = json.loads(old[old.index("{"):old.rindex("}") + 1])
pn = json.load(open(BA + "/pairs-new.json"))
extra = json.load(open(BA + "/pairs-v2new.json")) if os.path.exists(BA + "/pairs-v2new.json") else {"groups": [], "pairs": []}
groups = pn["groups"] + extra["groups"]
img = set(os.listdir(BA + "/img")) if os.path.isdir(BA + "/img") else set()
pth = lambda f: ("ba/" + f) if f in img else None
pairs = []
for p in pn["pairs"] + extra["pairs"]:
    q = dict(p); q["before"] = q.get("before") or pth(p["id"] + "-before.png"); q["v1"] = q.get("v1") or pth(p["id"] + "-v1.png")
    pairs.append(q)
shots = {}
for p in old["pairs"] + pairs:
    f = pth(p["id"] + "-v2.png")
    if f: shots[p["id"]] = f
# Which pair a note belongs to: its route, or a route the pair lists in "also"; a preview or dialog note goes to the record pair of a shared route.
RECORD = {"risks": "risk-record", "checks": "test-page", "evidence": "evidence-record", "policies": "policy-record", "integrations": "integration-drawer",
          "people": "person-drawer", "people-access": "access-review", "suppliers": "supplier-record"}
index = {}
for p in old["pairs"] + pairs:
    for r in [p.get("route")] + (p.get("also") or []):
        if r and r not in index: index[r] = p["id"]
for p in old["pairs"]:
    if p.get("afterRoute"): index.setdefault(p["afterRoute"], p["id"])
    index.setdefault(p["id"], p["id"])
# Record pages of a register belong to its record pair.
PREFIX = [("policy-page", "policy-record"), ("policy-editor", "policy-editor"), ("evidence-page", "evidence-record"), ("check-", "test-page"), ("person-", "person-drawer"),
          ("stigs-", "stig-record"), ("campaign-", "audit-record"), ("control-si2", "control-record"), ("component-mc", "component-record"), ("findings-", "findings-deadlines"),
          ("poam-", "poam-tracker"), ("risks-", "risk-register"), ("people-access", "access-reviews"), ("people-task", "role-task-sets"), ("inventory-", "inventory"),
          ("assessments-", "audits-index"), ("frameworks-", "frameworks"), ("sources-", "evidence-sources"), ("integration-", "integration-drawer"), ("program-start", "new-program-page"), ("program-new", "program-new"),
          ("ssp-", "ssp"), ("plan-", "ssps"), ("deadlines", "settings"), ("notifications-", "notifications"), ("lifecycle-", "new-gate-pdr")]
notes, unplaced = {}, []
for f in sorted(glob.glob(V + "/v2/*/notes.json")):
    who = os.path.basename(os.path.dirname(f))
    try: L = json.load(open(f))
    except Exception as e: print("skip", f, e); continue
    if isinstance(L, dict): L = L.get("notes", [])
    for n in L:
        r = (n.get("route") or "").strip()
        where = n.get("where") or ""
        pid = n.get("pair") or (RECORD.get(r) if where.startswith(("preview", "dialog")) and r in RECORD else None) or index.get(r)
        if not pid:
            pid = next((v for k, v in PREFIX if r.startswith(k)), None)
        if not pid:
            base = re.sub(r"-[a-z0-9]+$", "", r)
            pid = index.get(base)
        item = {"finding": n.get("finding") or "", "text": n.get("text") or "", "by": who}
        if where: item["where"] = where
        if pid: notes.setdefault(pid, []).append(item)
        else: unplaced.append({**item, "route": r})
fl = {}
for name in ["distance", "flows", "noise"]:
    d = json.load(open(V + "/gap/" + name + "/findings.json")); L = d if isinstance(d, list) else d.get("findings", [])
    for x in L:
        t = (x.get("we_do") or "").split(". ")[0]
        fl[x["id"]] = (t[:160] + "…") if len(t) > 160 else t
summ = json.load(open(BA + "/v2sum.json")) if os.path.exists(BA + "/v2sum.json") else {}
out = {"groups": groups, "pairs": pairs, "shots": shots, "notes": notes, "findings": fl, "v2": summ, "unplaced": unplaced}
open(V + "/proto/mod-zz-compare-v2.js", "w").write("// Generated by v2/ba/badata2.py: the v2 screenshots, the screens added since version 6, and what v2 changed on each screen.\nwindow.PA.BA2 = " + json.dumps(out, ensure_ascii=False) + ";\n")
print("pairs", len(old["pairs"]), "+", len(pairs), "| v2 shots", len(shots), "| notes", sum(len(v) for v in notes.values()), "on", len(notes), "screens | unplaced", len(unplaced))
for u in unplaced[:12]: print("  unplaced:", u["route"], "|", u["text"][:80])
