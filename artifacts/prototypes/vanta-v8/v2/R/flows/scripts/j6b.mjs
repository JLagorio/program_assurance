import { start } from "./walk.mjs";
const W = await start("j6b");
const prim = async () => { const b = await W.see("#modal"); const p = b.filter(x => /^button/.test(x) && !/Cancel|✕|Back/.test(x)).pop(); return p ? p.split(": ").slice(1).join(": ") : null; };
await W.go("campaign-r2");
console.log("R2:", (await W.text("#main", 700)).replace(/\s+/g, " ").slice(0, 450));
let e = await W.click("Accept", { within: "#main", exact: true, why: "assessor accepts", wait: 500 });
console.log("ACCEPT →", e && e.effect, "|", (await W.text("#modal", 1500)).replace(/\s+/g, " ").slice(0, 700));
let p = await prim(); e = await W.click(p, { within: "#modal", exact: true, why: "confirm", wait: 700 });
console.log("CONFIRM (" + p + ") →", e && e.effect);
console.log("R2 AFTER:", (await W.text("#main", 700)).replace(/\s+/g, " ").slice(0, 450));
await W.go("campaign");
const before = (await W.text("#main", 900)).replace(/\s+/g, " ").slice(0, 600);
console.log("CAMPAIGN:", before);
await W.shot("03-campaign");
