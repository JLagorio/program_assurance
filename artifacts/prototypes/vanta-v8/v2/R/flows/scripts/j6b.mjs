console.log("PUBLISH →", e && e.effect, "|", (await W.text("#modal", 2500)).replace(/\s+/g, " ").slice(0, 1200));
await W.shot("04-publish-dialog");
p = await prim(); e = await W.click(p, { within: "#modal", exact: true, why: "confirm publish", wait: 900 });
console.log("CONFIRM PUBLISH (" + p + ") →", e && e.effect);
console.log("CAMPAIGN AFTER:", (await W.text("#main", 900)).replace(/\s+/g, " ").slice(0, 600));
await W.go("assessments");
console.log("ASSESSMENTS AFTER:", (await W.text("#main", 700)).replace(/\s+/g, " ").slice(0, 400));
