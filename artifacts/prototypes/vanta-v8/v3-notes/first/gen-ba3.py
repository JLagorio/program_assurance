# Writes proto/mod-zzzz-v3-9ba-data.js (window.PA.BA3) from every V3 lane's notes: SP/vanta/v3/<lane>/notes.json.
# Copies each lane's screenshots to v3/pub/<file> (published beside the page as v3/<file>). Run: python3 -I v3/gen-ba3.py
import json, os, shutil, glob, sys
here = os.path.dirname(os.path.abspath(__file__))           # SP/vanta/v3
vanta = os.path.dirname(here)
pub = os.path.join(here, "pub"); os.makedirs(pub, exist_ok=True)
LANES = ["P", "G", "F", "R", "W", "X", "L"]
out = {"findings": {}, "walks": [], "extras": [], "shots": [], "checks": [], "lanes": {}, "missing": []}
rank = {"fixed": 3, "partly": 2, "not": 1}
for lane in LANES:
    p = os.path.join(here, lane, "notes.json")
    if not os.path.exists(p): continue
    try: n = json.load(open(p))
    except Exception as e: print("bad notes", lane, e); continue
    out["lanes"][lane] = {"findings": len(n.get("findings", [])), "walks": len(n.get("walks", [])), "shots": len(n.get("shots", []))}
    for f in n.get("findings", []):
        fid = f.get("id"); 
        if not fid: continue
        e = {"status": f.get("status"), "text": f.get("text", ""), "why": f.get("why", ""), "see": f.get("see"), "lane": lane}
        old = out["findings"].get(fid)
        if not old or rank.get(e["status"], 0) >= rank.get(old["status"], 0): out["findings"][fid] = e  # a later lane composes on an earlier one: its words win a tie
    for w in n.get("walks", []):
        steps = [s for s in w.get("steps", []) if s.get("do")]
        if steps: out["walks"].append({**w, "steps": steps, "lane": lane})
    for x in n.get("extra", []) or n.get("extras", []): out["extras"].append({**x, "lane": lane})
    for s in n.get("shots", []):
        ok = True
        for side in ("v2", "v3"):
            src = os.path.join(vanta, s.get(side, ""))
            if not s.get(side) or not os.path.exists(src): ok = False; out["missing"].append(s.get(side)); continue
            shutil.copyfile(src, os.path.join(pub, os.path.basename(src)))
            s[side] = "v3/" + os.path.basename(src)
        if ok: out["shots"].append({**s, "lane": lane})
cp = os.path.join(here, "checks.json")
if os.path.exists(cp): out["checks"] = json.load(open(cp))
js = "// Generated by SP/vanta/v3/gen-ba3.py from SP/vanta/v3/<lane>/notes.json. Never edit by hand.\n(function () { if (!window.PA) return; window.PA.BA3 = " + json.dumps(out, ensure_ascii=False) + "; })();\n"
open(os.path.join(vanta, "proto", "mod-zzzz-v3-9ba-data.js"), "w").write(js)
st = {}
for f in out["findings"].values(): st[f["status"]] = st.get(f["status"], 0) + 1
print("BA3:", len(out["findings"]), "findings", st, "|", len(out["walks"]), "walks |", len(out["shots"]), "shots |", len(out["extras"]), "extras | lanes", out["lanes"], "| missing shots", out["missing"][:5])
