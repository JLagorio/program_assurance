import { createRequire } from "module";
const require = createRequire("/Users/joseflagorio/Development/program_assurance-ux-proposal/package.json");
const { chromium } = require("playwright");
const build = process.argv[2], out = process.argv[3];
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message)); p.on("console", (m) => { if (m.type() === "error") errs.push("console: " + m.text()); });
await p.goto("file://" + build + "#overview"); await p.waitForTimeout(700);
await p.evaluate(() => { sessionStorage.clear(); PA.v2.reset(); PA.v3.set(true); }); await p.waitForTimeout(300);
const go = async (r) => { await p.evaluate((r) => { location.hash = r; }, r); await p.waitForTimeout(400); };
const ok = (n, c) => console.log(c ? "ok  " : "FAIL", n);
await go("k3-demo"); await p.waitForTimeout(2600);
await p.screenshot({ path: `${out}/kit-1.jpg`, type: "jpeg", quality: 70, fullPage: true });
ok("page drawn", await p.evaluate(() => !!document.querySelector("#main .k3-title")));
ok("menu item on", await p.evaluate(() => /Controls/.test((document.querySelector("#nav .on, #nav [aria-current]") || {}).innerText || "")));
await p.click(".k3-rail-i:nth-of-type(2)"); await p.waitForTimeout(200);
ok("rail filters to AC (2 rows)", await p.evaluate(() => document.querySelectorAll("#main .k3-table")[0].querySelectorAll("tbody tr").length === 2));
await p.fill(".k3-search input", "lock"); await p.waitForTimeout(450);
ok("search narrows to 1 and keeps focus", await p.evaluate(() => document.querySelectorAll("#main .k3-table")[0].querySelectorAll("tbody tr").length === 1 && document.activeElement.matches(".k3-search input")));
await p.fill(".k3-search input", ""); await p.waitForTimeout(450);
await p.click("#main .k3-sec .btn"); await p.waitForTimeout(200);
ok("form open", await p.evaluate(() => !document.getElementById("modal").hidden && !!document.querySelector(".k3-form")));
await p.click("[data-k3-submit]"); await p.waitForTimeout(150);
ok("required refused (3 errors)", await p.evaluate(() => document.querySelectorAll(".k3-f.bad").length === 3));
await p.selectOption("#k3f-kind", "Software"); await p.fill("#k3f-version", "2.0"); await p.fill("#k3f-name", "Mission OS");
await p.screenshot({ path: `${out}/kit-form.jpg`, type: "jpeg", quality: 70 });
await p.click("[data-k3-submit]"); await p.waitForTimeout(300);
ok("item added, dialog closed, toast", await p.evaluate(() => document.getElementById("modal").hidden && /Mission OS/.test(document.querySelector("#main").innerText) && /added/.test((document.getElementById("v2-toast") || {}).innerText || "")));
await p.click("#main .k3-head-a .btn.ink"); await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/kit-pick.jpg`, type: "jpeg", quality: 70 });
ok("picker lists 3, one held", await p.evaluate(() => document.querySelectorAll(".k3-pick-i").length === 3 && document.querySelectorAll(".k3-pick-i.held").length === 1));
await p.click(".k3-pick-i:not(.held) input"); await p.waitForTimeout(100);
ok("picker button counts", await p.evaluate(() => /Add 1 control$/.test(document.querySelector("[data-k3-submit]").innerText)));
await p.keyboard.press("Escape"); await p.waitForTimeout(150);
ok("escape closes", await p.evaluate(() => document.getElementById("modal").hidden));
await p.click("#main .k3-table tbody tr"); await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/kit-panel.jpg`, type: "jpeg", quality: 70 });
ok("panel open with anatomy", await p.evaluate(() => !document.getElementById("panel").hidden && !!document.querySelector("#panel .k3-pn h4")));
await p.click('#panel .bar-top button[aria-label="Open the full record"]'); await p.waitForTimeout(400);
ok("↗ opens the record page", await p.evaluate(() => /^#k3-demo--[a-z]$/.test(location.hash) && !!document.querySelector("#main .k3-crumbs")));
await p.click(".k3-tabs a:nth-child(2)"); await p.waitForTimeout(400);
ok("record tab by address", await p.evaluate(() => /--reqs$/.test(location.hash) && /reqs/.test(document.querySelector("#main").innerText)));
await p.screenshot({ path: `${out}/kit-record.jpg`, type: "jpeg", quality: 70 });
await p.evaluate(() => PA.v3.set(false)); await p.waitForTimeout(300);
ok("V3 off: says it belongs to V3", await p.evaluate(() => /Part of V3/.test(document.querySelector("#main").innerText)));
await p.evaluate(() => PA.v3.set(true)); await p.setViewportSize({ width: 390, height: 800 }); await go("k3-demo"); await p.waitForTimeout(300);
ok("390: no sideways scroll", await p.evaluate(() => document.documentElement.scrollWidth <= 390 && document.getElementById("main").scrollWidth <= document.getElementById("main").clientWidth + 1));
await p.screenshot({ path: `${out}/kit-390.jpg`, type: "jpeg", quality: 70, fullPage: true });
console.log("errors", errs.slice(0, 6));
await b.close();
