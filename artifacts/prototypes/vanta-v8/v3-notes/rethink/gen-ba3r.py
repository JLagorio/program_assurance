# Before & after › V3, rethought: what each lane of the rethink did, as window.PA.BA3R (proto/mod-zzzz-v3-9bb-data.js).
# Reads v3r/<LANE>/notes.json (pages, folded, inplace, walks, shots, open), v3r/said.json and v3r/checks.json; copies the lanes'
# screenshots into v3/pub as r-<file> (published as v3/r-<file>).
import json, os, shutil, sys
SP = "/private/tmp/claude-501/-Users-joseflagorio-Development-program-assurance-design-system/594d4d59-1431-4a4a-b8c7-702716989aa1/scratchpad"
V = SP + "/vanta"; R = V + "/v3r"; PUB = V + "/v3/pub"
LANES = [("O", "Overview"), ("S", "System"), ("C", "Controls"), ("D", "Documents, requirements, evidence"), ("E", "Assessments, findings, risks, authorization")]
os.makedirs(PUB, exist_ok=True)
out = {"said": json.load(open(R + "/said.json")), "pages": [], "folded": [], "inplace": [], "walks": [], "shots": [], "open": [], "lanes": [], "checks": [], "jobs": None}
missing = []
for L, name in LANES:
    p = f"{R}/{L}/notes.json"
    if not os.path.exists(p): missing.append(L); continue
    d = json.load(open(p)); out["lanes"].append(L)
    for x in d.get("pages", []): out["pages"].append(dict(x, lane=L))
    for x in d.get("folded", []): out["folded"].append(dict(x, lane=L))
    for x in d.get("inplace", []): out["inplace"].append(dict(x, lane=L))
    for w in d.get("walks", []): out["walks"].append(dict(w, lane=L, prog=w.get("prog", "wsx")))
    for s in d.get("shots", []):
        s2 = dict(s, lane=L)
        for k in ("was", "now"):
            src = s.get(k)
            if not src: continue
            f = src if os.path.isabs(src) else (V + "/" + src if src.startswith("v3r/") else f"{R}/{L}/" + src)
            if os.path.exists(f):
                name2 = "r-" + os.path.basename(f); shutil.copyfile(f, PUB + "/" + name2); s2[k] = "v3/" + name2
            else: s2[k] = None; print("missing shot", f, file=sys.stderr)
        if s2.get("now"): out["shots"].append(s2)
    for o in d.get("open", []): out["open"].append({"lane": L, "text": o})
for f, k in (("checks.json", "checks"), ("jobs.json", "jobs")):
    if os.path.exists(R + "/" + f): out[k] = json.load(open(R + "/" + f))
open(V + "/proto/mod-zzzz-v3-9bb-data.js", "w").write("// Generated by SP/vanta/v3r/gen-ba3r.py from the rethink lanes' notes. Do not edit.\nwindow.PA.BA3R = " + json.dumps(out, ensure_ascii=False) + ";\n")
print("BA3R: lanes", out["lanes"], "missing", missing, "| pages", len(out["pages"]), "folded", len(out["folded"]), "in place", len(out["inplace"]), "walks", len(out["walks"]), "shots", len(out["shots"]), "open", len(out["open"]))
