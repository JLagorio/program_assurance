import { open } from "./lib.mjs";
const { b, p, errs, go } = await open();
const out = await p.evaluate(() => {
  const r = {};
  const cut = (s, n) => (s && s.length > n ? s.slice(0, n) + " …" : s);
  const T = (html) => { const t = document.createElement("template"); t.innerHTML = html; return t.content; };
  const pol = T(PA.S.policies());
  r.polRow = cut([...pol.querySelectorAll("tbody tr")].slice(0, 2).map((x) => x.outerHTML.replace(/<svg.*?<\/svg>/g, "")).join("\n"), 1800);
  r.polStates = JSON.stringify([...pol.querySelectorAll("tbody tr")].map((tr) => (tr.children[2] ? tr.children[2].textContent.trim() : "")));
  r.polHead = cut(pol.querySelector("table").previousElementSibling ? pol.querySelector("table").parentElement.parentElement.previousElementSibling.outerHTML.replace(/<svg.*?<\/svg>/g, "") : "", 600);
  const it = T(PA.S.itcsc());
  r.itHead = cut((it.querySelector(".hd, header, .ak-rh, .ak-ih") || it.firstElementChild).outerHTML.replace(/<svg.*?<\/svg>/g, ""), 1500);
  const sp = T(PA.S.ssps());
  r.sspsTop = cut(sp.firstElementChild.innerHTML.replace(/<svg.*?<\/svg>/g, "").slice(0, 2600), 2600);
  r.customer = JSON.stringify(PA.v3.fact("customer")).slice(0, 900);
  r.follow = JSON.stringify(PA.v2reqs.follow("REQ-001")).slice(0, 700);
  r.follow2 = JSON.stringify(PA.v2reqs.follow("REQ-248")).slice(0, 900);
  r.owner = String(PA.v7p.owner).slice(0, 300);
  r.evopts = JSON.stringify(PA.v2.chain.EV_OPTS()).slice(0, 500);
  r.people = JSON.stringify((PA.v3.fact("people", "PRG-1090") || []).slice(0, 12)).slice(0, 900);
  r.today = PA.v2.chain.TODAY_ISO + " " + PA.v2.chain.ME;
  const comp = T(PA.S["requirements-compliance"]());
  r.compTop = cut(comp.firstElementChild.innerHTML.replace(/<svg.*?<\/svg>/g, "").replace(/<table[\s\S]*<\/table>/, "[table]"), 2500);
  r.hubs = Object.keys(PA.v2hubs).join(" ");
  return r;
});
for (const [k, v] of Object.entries(out)) console.log(k, "=", typeof v === "string" ? v : JSON.stringify(v), "\n");
console.log("errors", errs.slice(0, 5));
await b.close();
