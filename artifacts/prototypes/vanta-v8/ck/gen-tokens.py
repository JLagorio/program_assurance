# Build ../src/mod-zzzz-v5-ck.css from ck.src.css: every Canvas Kit token the stylesheet uses (var(--cnvs-…)), with the
# tokens they refer to, copied from @workday/canvas-tokens-web 4.x (Apache-2.0) into one block scoped to the mockups.
#   npm pack @workday/canvas-tokens-web@4 && tar xzf workday-canvas-tokens-web-*.tgz
#   python3 -I gen-tokens.py <path to the unpacked package>
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
pkg = sys.argv[1]
defs = {}
for part in ("base", "brand", "system"):
    for name, val in re.findall(r"^\s*(--cnvs-[\w-]+):\s*([^;]+);", open(os.path.join(pkg, "css", part, "_variables.css")).read(), re.M):
        defs.setdefault(name, val.strip())
src = open(os.path.join(here, "ck.src.css")).read()
need, todo = set(), re.findall(r"var\((--cnvs-[\w-]+)", src)
while todo:
    n = todo.pop()
    if n in need: continue
    if n not in defs: sys.exit("unknown token " + n)
    need.add(n); todo += re.findall(r"var\((--cnvs-[\w-]+)", defs[n])
version = re.search(r'"version":\s*"([^"]+)"', open(os.path.join(pkg, "package.json")).read()).group(1)
block = "/* Canvas Kit tokens, @workday/canvas-tokens-web %s (Apache-2.0, Workday, Inc.): the %d this page uses. Generated by ck/gen-tokens.py. */\n.ck-app {\n%s\n}\n" % (
    version, len(need), "\n".join("  %s: %s;" % (n, defs[n]) for n in sorted(need)))
open(os.path.join(here, "..", "src", "mod-zzzz-v5-ck.css"), "w").write(block + src)
print("wrote src/mod-zzzz-v5-ck.css with %d tokens from %s" % (len(need), version))
