import { start } from "./walk.mjs";
const W = await start("j4e");
await W.go("evidence");
await W.click("Time source comparison test report", { wait: 500 });
let e = await W.click("Accept", { within: "#panel", exact: true, why: "reviewer accepts", wait: 500 });
console.log("ACCEPT →", e && e.effect);
console.log("DIALOG:", (await W.text("#modal", 1500)).replace(/\s+/g, " ").slice(0, 900));
console.log("DIALOG CONTROLS:", (await W.see("#modal")).join(" ‖ "));
await W.shot("06-accept-dialog");
const btns = await W.see("#modal");
const primary = btns.filter(b => /button/.test(b) && !/Cancel|✕/.test(b)).pop();
console.log("PRIMARY:", primary);
const label = primary ? primary.split(": ").slice(1).join(": ") : "Accept";
e = await W.click(label, { within: "#modal", exact: true, why: "confirm", wait: 700 });
console.log("CONFIRM →", e && e.effect);
console.log("PANEL AFTER:", (await W.text("#panel", 900)).replace(/\s+/g, " ").slice(0, 500));
const counts = await W.p.evaluate(() => document.getElementById("main").innerText.match(/Pending review\s*(\d+)|Accepted\s*(\d+)/g));
console.log("REGISTER COUNTS:", counts);
const row = await W.p.evaluate(() => { const r = document.querySelector("#main table tbody tr"); return r ? r.innerText.replace(/\s+/g, " ").slice(0, 200) : null; });
console.log("ROW1:", row);
await W.shot("07-after-accept");
await W.done();
