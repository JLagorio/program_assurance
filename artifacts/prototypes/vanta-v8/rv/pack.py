# Bundle ck/*.jpg and rv/*.jpg into a few pack files (JPEGs end to end), since one artifact version holds at most 512 files.
#   python3 -I rv/pack.py   (from artifacts/prototypes/vanta-v8; then rebuild)
# Writes src/out/pk/pack-<n>.jpg (publish them as pk/pack-<n>.jpg) and src/mod-zzzz-v7-pack-data.js, the index
# mod-zzzz-v7-pack.js reads: an <img> whose src is a packed path is given its bytes from the pack.
# Opened from the file, the packs do not load and the images load from ck/ and rv/ as before.
import glob, json, os
files = sorted(glob.glob("ck/*.jpg")) + sorted(glob.glob("rv/*.jpg"))
os.makedirs("src/out/pk", exist_ok=True)
for f in glob.glob("src/out/pk/*.jpg"): os.remove(f)
LIMIT = 2_000_000
index, packs, cur, n, off = {}, [], bytearray(), 0, 0
def flush():
    global cur, n
    if cur:
        open(f"src/out/pk/pack-{n}.jpg", "wb").write(cur); packs.append(f"pk/pack-{n}.jpg"); n += 1; cur = bytearray()
for f in files:
    b = open(f, "rb").read()
    if cur and len(cur) + len(b) > LIMIT: flush()
    index[f] = [n, len(cur), len(b)]; cur += b
flush()
open("src/mod-zzzz-v7-pack-data.js", "w").write("// Generated by rv/pack.py: path → [pack, offset, length].\nwindow.PA_PACK = " + json.dumps({"packs": packs, "files": index}, separators=(",", ":")) + ";\n")
print(len(files), "files in", len(packs), "packs")
