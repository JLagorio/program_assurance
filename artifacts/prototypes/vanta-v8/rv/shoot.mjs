// Shoot every Review all screen as v2 (V3 off, WS-X90) at 1440×900, and as V3 where no ck/cur-<id>.jpg exists:
//   node rv/shoot.mjs <build.html> <rv-dir> [screen-key …]
// Writes <rv-dir>/v2-<key>.jpg and v3-<key>.jpg (q60) and src/mod-zzzz-v6-review-data.js (PA.RVSHOTS, the shots taken;
// 0 where v2 has no page for the screen: its "Part of V3" stub, or a route v2 does not know, which falls through to Home).
// Run after the Canvas Kit mockups change, then rebuild (python3 -I build.py prototype in src/).
import { createRequire } from "module";
const { chromium } = createRequire(import.meta.url)("playwright");
import fs from "fs";
import path from "path";
import crypto from "crypto";
const [build, out, ...only] = process.argv.slice(2);
const here = path.dirname(new URL(import.meta.url).pathname);
const dataFile = path.join(here, "..", "src", "mod-zzzz-v6-review-data.js");
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
await page.goto("file://" + path.resolve(build) + "#overview");
await page.waitForTimeout(800);
await page.evaluate(() => { sessionStorage.clear(); if (PA.v2 && PA.v2.reset) PA.v2.reset(); });
await page.waitForTimeout(4500);
await page.addStyleTag({ content: "#v2-toast, #rv-fab, .rv-toast { display: none !important; }" });
const list = await page.evaluate(() => PA.rv.screens().map((s) => ({ key: s.key, route: s.route, pattern: s.pattern, ck: s.ck, v3img: s.v3img || null })));
const safe = (s) => String(s).replace(/[^A-Za-z0-9_-]/g, "_");
const ckDir = path.join(path.dirname(path.resolve(build)), "..", "..", "ck");
const ckHere = (id) => [path.join(path.resolve(out), "..", "ck", `cur-${id}.jpg`), path.join(ckDir, `cur-${id}.jpg`)].some((f) => fs.existsSync(f));
let shots = {};
try { const s = fs.readFileSync(dataFile, "utf8"); shots = JSON.parse(s.slice(s.indexOf("{", s.indexOf("RVSHOTS")), s.lastIndexOf("}") + 1)); } catch (e) { shots = {}; }
let n = 0;
const md5 = (b) => crypto.createHash("md5").update(b).digest("hex");
let homeMd5 = null;
// Returns false where v2 has no page for the route (nothing is written).
async function shoot(route, v3, file) {
  await page.evaluate(([r, on]) => {
    document.querySelectorAll("[data-close-modal]").forEach((b) => b.click());
    if (PA.v2hubs && PA.v2hubs.cur() !== "PRG-1090") PA.v2hubs.setCur("PRG-1090");
    if (PA.v3.on() !== on) PA.v3.set(on, { redraw: false });
    const r2 = on ? r : (PA.v3.wasOf && PA.v3.wasOf(r)) || r;
    location.hash = "before-after";
    setTimeout(() => { location.hash = r2; }, 50);
  }, [route, v3]);
  await page.waitForTimeout(1200);
  await page.mouse.move(5, 895);
  const stub = await page.evaluate(() => !!document.querySelector("#main .v3-off"));
  const buf = await page.screenshot({ type: "jpeg", quality: 60 });
  const v2r = await page.evaluate((r) => (PA.v3.wasOf && PA.v3.wasOf(r)) || r, route);
  if (!v3 && (stub || (v2r !== "home" && homeMd5 && md5(buf) === homeMd5))) {
    console.log("v2 has no page for", route, stub ? "(V3 stub)" : "(falls through to Home)");
    fs.rmSync(path.join(out, file), { force: true });
    return false;
  }
  fs.writeFileSync(path.join(out, file), buf);
  n++;
  return true;
}
// v2's Home, to tell a route v2 does not know (it draws Home) from a real page.
{ const f = path.join(out, ".home-probe.jpg"); await shoot("home", false, ".home-probe.jpg"); homeMd5 = md5(fs.readFileSync(f)); fs.rmSync(f); n--; }
for (const s of list) {
  if (only.length && !only.includes(s.key)) continue;
  if (s.pattern || !s.route) continue;
  const k = safe(s.key);
  shots["v2-" + k] = (await shoot(s.route, false, `v2-${k}.jpg`)) ? 1 : 0;
  if (!(s.ck && ckHere(s.ck)) && !s.v3img) { await shoot(s.route, true, `v3-${k}.jpg`); shots["v3-" + k] = 1; }
}
fs.writeFileSync(dataFile, `// Generated by rv/shoot.mjs: the screenshots it took, by name; do not edit.\nwindow.PA = window.PA || {};\nwindow.PA.RVSHOTS = ${JSON.stringify(shots, null, 0)};\n`);
console.log(`${n} shots of ${list.length} screens; page errors: ${errs.length}${errs.length ? " " + [...new Set(errs)].slice(0, 3).join(" | ") : ""}`);
await browser.close();
