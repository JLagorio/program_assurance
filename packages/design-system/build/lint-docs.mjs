// Generate the lint rules' documentation from their pages. Each rule has one page,
// `eslint-plugin/docs/<rule>.md`, which ships with the plugin and which the rule's `meta.docs.url`
// points at. From them this writes the rule rows of the Lint rules page's table
// (`src/stories/docs/Lint.mdx`, between its markers) and the Lint rules reference page
// (`src/stories/docs/LintRules.mdx`), which carries every page so the Storybook, its MCP server and
// `llms.txt` read them. It also writes the table of shadcn's theme names on the Coming from shadcn
// page (`src/stories/docs/FromShadcn.mdx`, between its markers) from the aliases the token build
// checked. Run by `npm run build:lint`, after the inventory. Keep this file build-only; the outputs
// are committed and tested for drift (test/lint-docs.test.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import plugin from "../eslint-plugin/index.js";
import { pageTitle } from "./llms.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(root, "../..");
export const docsDir = path.join(root, "eslint-plugin/docs");
export const lintPagePath = path.join(root, "src/stories/docs/Lint.mdx");
export const referencePath = path.join(root, "src/stories/docs/LintRules.mdx");

/** The headings of a rule's page, in order; Examples holds Reported, then Allowed. */
export const SECTIONS = [
  "Reports",
  "Why",
  "Instead",
  "Examples",
  "Suggestions and fixes",
  "Allowances",
  "Limits",
];
export const EXAMPLE_KINDS = ["Reported", "Allowed"];

export const REFERENCE_TITLE = "Guidance/Lint rules reference";
const LINT_TITLE = "Guidance/Lint rules";
const START =
  "{/* lint-docs: rules start. Generated by build/lint-docs.mjs from eslint-plugin/docs; edit a rule's page there and run npm run build:lint. */}";
const END = "{/* lint-docs: rules end */}";

/* ---------- reading a page ---------- */

const FENCE = /^\s*(`{3,}|~{3,})(.*)$/;

/** Markdown lines with whether each is inside a fenced block, its opening and closing lines included. */
function fencedLines(source) {
  let fence = null;
  return source.split("\n").map((line) => {
    const match = FENCE.exec(line);
    if (fence) {
      if (
        match &&
        match[1][0] === fence[0] &&
        match[1].length >= fence.length &&
        !match[2].trim()
      ) {
        fence = null;
        return { line, fenced: true, close: true };
      }
      return { line, fenced: true };
    }
    if (match) {
      fence = match[1];
      return { line, fenced: true, info: match[2].trim() };
    }
    return { line, fenced: false };
  });
}

/**
 * One rule's page, read into its parts: the `# ledger/<rule>` title, the one-sentence summary
 * under it, its `##` sections in order with their bodies, and the fenced examples. An example's
 * info string says `reported` or `allowed`, and may name the path it is linted at (`path=…`).
 */
export function parsePage(source, file = "page.md") {
  const lines = fencedLines(source.replace(/\r\n/g, "\n"));
  const title = /^# (.+)$/.exec(lines.find(({ line }) => line.trim())?.line ?? "")?.[1]?.trim();
  const sections = [];
  const summary = [];
  const examples = [];
  let current = null;
  let subsection = null;
  let example = null;
  lines.forEach(({ line, fenced, info, close }, index) => {
    if (!fenced) {
      const heading = /^(#{2,3}) (.+)$/.exec(line);
      if (heading?.[1] === "##") {
        current = { heading: heading[2].trim(), lines: [], subsections: [] };
        subsection = null;
        sections.push(current);
        return;
      }
      if (heading?.[1] === "###" && current) {
        subsection = heading[2].trim();
        current.subsections.push(subsection);
      }
    }
    if (info !== undefined) {
      const words = info.split(/\s+/);
      const kind = words.find((word) => word === "reported" || word === "allowed");
      if (kind)
        example = {
          kind,
          lang: words[0],
          path: words.find((word) => word.startsWith("path="))?.slice("path=".length),
          section: current?.heading,
          subsection,
          line: index + 1,
          code: [],
        };
    } else if (close && example) {
      examples.push({ ...example, code: example.code.join("\n") + "\n" });
      example = null;
    } else if (example) example.code.push(line);
    if (current) current.lines.push(line);
    else if (!/^# /.test(line)) summary.push(line);
  });
  return {
    file,
    source,
    rule: title?.replace(/^ledger\//, ""),
    title,
    summary: summary.join("\n").trim(),
    sections: sections.map(({ heading, lines: body, subsections }) => ({
      heading,
      subsections,
      body: body.join("\n").trim(),
    })),
    examples,
  };
}

/** Every page in eslint-plugin/docs, by rule, from its file name. */
export function readPages(dir = docsDir) {
  if (!fs.existsSync(dir)) return new Map();
  return new Map(
    fs
      .readdirSync(dir)
      .filter((name) => name.endsWith(".md"))
      .sort()
      .map((name) => [
        name.slice(0, -".md".length),
        parsePage(fs.readFileSync(path.join(dir, name), "utf8"), path.join(dir, name)),
      ]),
  );
}

/* ---------- presets ---------- */

const WORDS = { 0: "off", 1: "warn", 2: "error" };
const word = (setting) => {
  const value = Array.isArray(setting) ? setting[0] : setting;
  return WORDS[value] ?? value;
};
/** A preset's own setting for a rule: its first, unscoped entry, as a word. */
export function presetSeverity(preset, rule) {
  const entries = plugin.configs[preset];
  const base = (Array.isArray(entries) ? entries : [entries]).find((entry) => !entry.files);
  return word(base?.rules?.[`ledger/${rule}`] ?? "off");
}

/** The package preset's scoped entries that set a rule, by what they scope to. */
const scopedIn = (pattern, rule) =>
  plugin.configs.package.some(
    (entry) =>
      entry.files?.some((glob) => pattern.test(glob)) && `ledger/${rule}` in (entry.rules ?? {}),
  );

// Footnotes about a rule itself rather than where a preset scopes it: the page's numbered notes.
const RULE_NOTES = { "no-inline-config": "⁵" };

/** A preset cell: the severity and the page's footnote marks. */
function presetCell(preset, rule) {
  const severity = presetSeverity(preset, rule);
  let marks = RULE_NOTES[rule] ?? "";
  if (preset === "package" && scopedIn(/stories/, rule)) marks = `¹${marks}`;
  if (preset === "package" && scopedIn(/bleed/, rule)) marks = `²${marks}`;
  if (preset === "recommended" && presetSeverity("package", rule) === "off" && severity === "off")
    marks = `³${marks}`;
  return `${severity}${marks}`;
}

/**
 * The table's order: the recommended preset's errors in its own order, then its warnings, then
 * the rules it leaves off (the opt-in ones), then any rule no preset names, as the plugin lists them.
 */
export function ruleOrder() {
  const listed = Object.keys(
    plugin.configs.recommended.find((entry) => !entry.files)?.rules ?? {},
  ).map((key) => key.replace(/^ledger\//, ""));
  const names = Object.keys(plugin.rules);
  const rank = (rule) =>
    ({ error: 0, warn: 1 })[presetSeverity("recommended", rule)] ?? (listed.includes(rule) ? 2 : 3);
  const at = (rule) => (listed.includes(rule) ? listed.indexOf(rule) : listed.length);
  return [...names].sort(
    (a, b) => rank(a) - rank(b) || at(a) - at(b) || names.indexOf(a) - names.indexOf(b),
  );
}

/* ---------- Markdown into MDX ---------- */

/** Storybook's id for a docs page title, as its sidebar sanitises one. */
export const storyId = (title) =>
  `${title
    .toLowerCase()
    .replace(/[ ’–—―′¿'`~!@#$%^&*()_|+\-=?;:'",.<>{}[\]\\/]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-+|-+$/g, "")}--docs`;

/** The id a heading gets in the Storybook, as github-slugger makes it from the heading's text. */
export const headingId = (text) =>
  text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\p{M}\p{Pc} -]/gu, "")
    .replace(/ /g, "-");

/** A link to a rule's section on the reference page, from anywhere in the Storybook. */
export const referenceLink = (rule) =>
  `?path=/docs/${storyId(REFERENCE_TITLE)}#${headingId(`ledger/${rule}`)}`;

/**
 * A link's target as the Storybook reads it. A page's links are relative to eslint-plugin/docs:
 * another rule's page becomes its section here, a Storybook page its `?path=`, and a file in the
 * repository its path as code, since the Storybook cannot open it.
 */
function relink(text, target, { inPage }) {
  if (/^([a-z]+:|#|\?path=)/i.test(target)) return `[${text}](${target})`;
  const [file] = target.split("#");
  const resolved = path.resolve(docsDir, file);
  if (path.dirname(resolved) === docsDir && resolved.endsWith(".md")) {
    const rule = path.basename(resolved, ".md");
    const anchor = `#${headingId(`ledger/${rule}`)}`;
    return `[${text}](${inPage ? anchor : referenceLink(rule)})`;
  }
  if (resolved.endsWith(".mdx") && fs.existsSync(resolved))
    return `[${text}](?path=/docs/${storyId(pageTitle(resolved, fs.readFileSync(resolved, "utf8")))})`;
  const shown = path.relative(repo, resolved).split(path.sep).join("/");
  return text.replace(/`/g, "") === shown ? `\`${shown}\`` : `${text} (\`${shown}\`)`;
}

/**
 * A line split into prose and code spans, prose first and then alternating, as CommonMark reads a
 * span: a run of backticks up to the next run of the same length, so `` `${size}px` `` is one span.
 * A run with no partner is prose.
 */
export function codeSpans(line) {
  const parts = [];
  let prose = "";
  let index = 0;
  while (index < line.length) {
    if (line[index] !== "`") {
      prose += line[index++];
      continue;
    }
    const run = /^`+/.exec(line.slice(index))[0];
    let close = -1;
    for (let at = index + run.length; at < line.length;) {
      const next = /`+/.exec(line.slice(at));
      if (!next) break;
      if (next[0].length === run.length) {
        close = at + next.index;
        break;
      }
      at += next.index + next[0].length;
    }
    if (close < 0) {
      prose += run;
      index += run.length;
      continue;
    }
    parts.push(prose, line.slice(index, close + run.length));
    prose = "";
    index = close + run.length;
  }
  parts.push(prose);
  return parts;
}

/**
 * A line of prose made safe for MDX: outside its code spans `<`, `{` and `}` are escaped, which
 * Markdown reads the same, and relative links follow `relink`, also when their text is code.
 */
export function proseToMdx(line, options = { inPage: true }) {
  const spans = [];
  const masked = codeSpans(line)
    .map((part, index) => (index % 2 ? `\u0000${spans.push(part) - 1}\u0000` : part))
    .join("");
  const restore = (text) => text.replace(/\u0000(\d+)\u0000/g, (_, at) => spans[Number(at)]);
  return restore(
    masked
      .replace(/(\\*)([<{}])/g, (whole, slashes, char) =>
        slashes.length % 2 ? whole : `${slashes}\\${char}`,
      )
      .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_, text, target) =>
        relink(restore(text), target, options),
      ),
  );
}

/** A page's Markdown as one section of the reference: headings one level down, prose MDX-safe. */
function pageToMdx(source) {
  return fencedLines(source.replace(/\r\n/g, "\n").trim())
    .map(({ line, fenced }) => {
      if (fenced) return line;
      if (/^#{1,5} /.test(line)) return `#${proseToMdx(line, { inPage: true })}`;
      return proseToMdx(line, { inPage: true });
    })
    .join("\n");
}

/* ---------- the table ---------- */

/** The first sentence of a block of prose, ignoring the stops inside code spans. */
export function firstSentence(text) {
  const parts = codeSpans(text.replace(/\s+/g, " ").trim());
  let sentence = "";
  for (const [index, part] of parts.entries()) {
    const stop = index % 2 ? -1 : part.search(/[.!?]( |$)/);
    // A stop that runs straight into a code span (`a.` then `` `b` ``) ends no sentence.
    if (stop >= 0 && (stop + 1 < part.length || index === parts.length - 1))
      return sentence + part.slice(0, stop + 1);
    sentence += part;
  }
  return sentence;
}

/**
 * The sentence a section leads with: the first of its first paragraph, or of its first item when
 * it opens with a list. The table shows it; the rule's section on the reference has the rest.
 */
export function leadOf(body) {
  const item = /^([-*+]|\d+\.) /;
  const lines = body.split("\n");
  const start = lines.findIndex((line) => line.trim());
  if (start < 0) return "";
  const block = [lines[start].replace(item, "")];
  for (const line of lines.slice(start + 1)) {
    if (!line.trim() || item.test(line)) break;
    block.push(line);
  }
  return firstSentence(block.join(" "));
}

const cell = (text) =>
  proseToMdx(text.replace(/\s+/g, " ").trim(), { inPage: false }).replace(/\|/g, "\\|");

/** A table row's cells for a rule, from its page, or from the old row while it has none. */
function rowCells(rule, page, previous) {
  const presets = [presetCell("package", rule), presetCell("recommended", rule)];
  if (!page) {
    const [reports = "", instead = ""] = previous ?? [];
    return [`\`${rule}\``, reports, instead, ...presets, ""];
  }
  const summary = firstSentence(page.summary)
    .replace(/^Reports /, "")
    .replace(/\.$/, "");
  const instead = page.sections.find(({ heading }) => heading === "Instead")?.body ?? "";
  return [
    `\`${rule}\``,
    cell(summary.charAt(0).toUpperCase() + summary.slice(1)),
    cell(leadOf(instead)),
    ...presets,
    `[ledger/${rule}](${referenceLink(rule)})`,
  ];
}

/**
 * A Markdown table, one row a line and no padding, so a long cell does not pad every other row
 * (llms.txt carries the page). Prettier would align it; the comment before it keeps it as written.
 */
function table(header, rows) {
  const line = (cells) => `| ${cells.join(" | ")} |`;
  return [
    "{/* prettier-ignore */}",
    line(header),
    line(header.map(() => "---")),
    ...rows.map(line),
  ].join("\n");
}

const HEADER = ["Rule", "Reports", "Instead", "`package`⁴", "`recommended`", "Page"];

/** The rows the Lint rules page holds now, by rule, so a rule without a page keeps its words. */
function previousRows(lintSource) {
  return new Map(
    lintSource
      .split("\n")
      .map((line) => /^\|\s*`([a-z-]+)`\s*\|(.*)\|\s*$/.exec(line))
      .filter(Boolean)
      .map(([, rule, rest]) => [rule, rest.split(/(?<!\\)\|/).map((text) => text.trim())]),
  );
}

/** The rules table, header and rows, with its markers. */
export function renderTable(pages, lintSource = "") {
  const previous = previousRows(lintSource);
  const rows = ruleOrder().map((rule) => rowCells(rule, pages.get(rule), previous.get(rule)));
  return [START, "", table(HEADER, rows), "", END].join("\n");
}

/** The Lint rules page with its table's rows regenerated between the markers. */
export function renderLintPage(lintSource, pages) {
  const start = lintSource.indexOf(START);
  const end = lintSource.indexOf(END);
  if (start < 0 || end < start)
    throw new Error(
      `${path.relative(root, lintPagePath)} has no lint-docs markers around its table.`,
    );
  return (
    lintSource.slice(0, start) + renderTable(pages, lintSource) + lintSource.slice(end + END.length)
  );
}

/* ---------- the reference page ---------- */

export function renderReference(pages) {
  const sections = ruleOrder()
    .filter((rule) => pages.has(rule))
    .map((rule) => pageToMdx(pages.get(rule).source));
  return (
    [
      'import { Meta } from "@storybook/addon-docs/blocks";',
      "",
      `<Meta title="${REFERENCE_TITLE}" />`,
      "",
      "{/* Generated by build/lint-docs.mjs from eslint-plugin/docs; edit a rule's page there and run npm run build:lint. */}",
      "",
      "# Lint rules reference",
      "",
      `Every rule of \`@ledger/design-system/eslint\`, one section each, from the pages the plugin ships in \`eslint-plugin/docs/\`, where each finding's \`meta.docs.url\` points. A section says what the rule reports, why, what to write instead, its fixes, its allowances and what it cannot see, with examples that \`test/lint-docs.test.mjs\` lints on every run: each reported example is reported by its rule and by no other, since a class has one owner, and each allowed example is reported by no rule. The [Lint rules](?path=/docs/${storyId(LINT_TITLE)}) page has the table of rules and presets.`,
      "",
      ...sections.flatMap((section) => [section, ""]),
    ]
      .join("\n")
      .trimEnd() + "\n"
  );
}

/** The rules the plugin ships that have no page yet. */
export const missingPages = (pages) => Object.keys(plugin.rules).filter((rule) => !pages.has(rule));

/* ---------- shadcn's theme names, on the Coming from shadcn page ---------- */

export const fromShadcnPath = path.join(root, "src/stories/docs/FromShadcn.mdx");
const VOCABULARY_START =
  "{/* lint-docs: theme names start. Generated by build/lint-docs.mjs from build/vocabulary-aliases.json, as the token build checked it into src/generated/lint-values.json; edit it there and run npm run build:tokens, then npm run build:lint. */}";
const VOCABULARY_END = "{/* lint-docs: theme names end */}";

/** The theme names as ledger/no-non-token-class reads them: lint-values.json's `aliases`. */
export const readAliases = () =>
  JSON.parse(fs.readFileSync(path.join(root, "src/generated/lint-values.json"), "utf8")).aliases;

/** An alias's words for a cell, with each class and part in them as code (`accent-*`,
    `border-t`, `Shell.SideNav`). */
const classesAsCode = (text) =>
  text.replace(/(?<![\w`.])(?:[a-z]+(?:-[a-z0-9*]+)+|[A-Z]\w*\.[A-Z]\w*)/g, "`$&`");

/** How the table names a state an alias keys (build/lint-data.mjs's ALIAS_STATES). */
const STATE_CELL = {
  selected: "on a selected, checked or pressed item",
  placeholder: "for a placeholder",
};

/** The theme names' table, with its markers: each name, what it is, and the Ledger class for its
    job, or the two and when each fits, the class under a state it keys, with the sentence its
    finding adds. */
export function renderVocabulary(aliases) {
  const rows = Object.entries(aliases).map(([name, { means, use, for: labels, aside, states }]) => [
    `\`${name}\``,
    cell(means.charAt(0).toUpperCase() + means.slice(1)),
    cell(
      [
        [
          use.map((cls, index) => `\`${cls}\`${labels ? ` for ${labels[index]}` : ""}`).join(", "),
          ...Object.entries(states ?? {}).map(([state, cls]) => `\`${cls}\` ${STATE_CELL[state]}`),
        ].join("; "),
        aside ? classesAsCode(aside) : "",
      ]
        .filter(Boolean)
        .join(". "),
    ),
  ]);
  return [
    VOCABULARY_START,
    "",
    table(["shadcn", "What it is", "In Ledger"], rows),
    "",
    VOCABULARY_END,
  ].join("\n");
}

/** The Coming from shadcn page with its theme names' table regenerated between the markers. */
export function renderFromShadcn(source, aliases) {
  const start = source.indexOf(VOCABULARY_START);
  const end = source.indexOf(VOCABULARY_END);
  if (start < 0 || end < start)
    throw new Error(
      `${path.relative(root, fromShadcnPath)} has no lint-docs markers around its theme names.`,
    );
  return (
    source.slice(0, start) + renderVocabulary(aliases) + source.slice(end + VOCABULARY_END.length)
  );
}

export function writeLintDocs() {
  const pages = readPages();
  fs.writeFileSync(lintPagePath, renderLintPage(fs.readFileSync(lintPagePath, "utf8"), pages));
  fs.writeFileSync(referencePath, renderReference(pages));
  fs.writeFileSync(
    fromShadcnPath,
    renderFromShadcn(fs.readFileSync(fromShadcnPath, "utf8"), readAliases()),
  );
  return { pages, missing: missingPages(pages) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { pages, missing } = writeLintDocs();
  console.log(
    `Lint rules: ${pages.size} pages${missing.length ? `; no page yet for ${missing.join(", ")}` : ""}`,
  );
}
