/** Where a control stands in the baseline. */
export type LadderStanding = "in" | "added" | "removed" | "out";
const standingOf: Record<string, LadderStanding> = { b: "in", a: "added", r: "removed", n: "out" };
/** The four standings in the order a row draws them, with how each is drawn and said: a TileMap's tones and fills. */
export const ladderStandings: readonly LadderStanding[] = ["in", "added", "removed", "out"];
export const ladderDrawn: Record<
  LadderStanding,
  { tone: TallyTone; fill: TallyFill; words: string }
> = {
  in: { tone: "neutral", fill: "solid", words: "In baseline" },
  added: { tone: "brand", fill: "solid", words: "Added" },
  removed: { tone: "warning", fill: "outline", words: "Removed" },
  out: { tone: "neutral", fill: "empty", words: "Not selected" },
};

export const ladderProgram = source.program;
/** The reference baseline, then each layer in the order it applies. */
export const ladderSteps: readonly string[] = source.steps;

const named = [...source.goals, ...source.objectives, ...source.techniques, ...source.approaches];
const codeAt = (index: number) => named[index]?.[0] ?? "";
/**
 * Every relation the publication prints: an approach to its technique first, which is where a row
 * stands, then an objective to a goal, a technique to an objective and an approach to an
 * objective, which passes over the techniques.
 */
export const ladderLinks: LadderLink[] = [
  ...source.approaches.map(([code, , technique]) => ({ from: code, to: technique })),
  ...source.supports.map(([from, to]) => ({ from: codeAt(from), to: codeAt(to) })),
];

const standingAt = (control: number, step: number): LadderStanding =>
  standingOf[source.controls[control]?.[2].charAt(step) ?? "n"] ?? "out";

// The controls behind each item. An approach's and a technique's are the table's own; an
// objective's are those of the approaches that support it, and a goal's those of its objectives.
const behind = new Map<string, number[]>();
for (const [code, , , , controls] of source.approaches) behind.set(code, controls);
for (const [code, , , controls] of source.techniques) behind.set(code, controls);
const supporters = (code: string) =>
  source.supports.filter(([, to]) => codeAt(to) === code).map(([from]) => codeAt(from));
const union = (codes: string[]) =>
  [...new Set(codes.flatMap((code) => behind.get(code) ?? []))].sort((a, b) => a - b);
for (const [code] of source.objectives)
  behind.set(code, union(supporters(code).filter((from) => from.startsWith("approach."))));
for (const [code] of source.goals) behind.set(code, union(supporters(code)));

/** How many of an item's controls stand where, after a step. */
function tally(controls: readonly number[], step: number) {
  const counts: Record<LadderStanding, number> = { in: 0, added: 0, removed: 0, out: 0 };
  for (const control of controls) counts[standingAt(control, step)] += 1;
  return counts;
}

function node(
  [code, title]: readonly [string, string, ...unknown[]],
  description: string,
  step: number,
) {
  const controls = behind.get(code) ?? [];
  const counts = tally(controls, step);
  const held = counts.in + counts.added;
  return {
    counts,
    held,
    controls,
    node: {
      id: code,
      title,
      description,
      value: held,
      total: controls.length,
      valueLabel: `${held} of ${controls.length} controls held`,
    } satisfies LadderNode,
  };
}

/** A goal, an objective or a technique: a card whose tally is what the baseline holds, adds and removes. */
function card(item: readonly [string, string, string, ...unknown[]], step: number): LadderNode {
  const { node: base, counts } = node(item, item[2], step);
  const segments: TallySegment[] = (["in", "added", "removed"] as const).map((standing) => ({
    key: standing,
    value: counts[standing],
    tone: ladderDrawn[standing].tone,
    fill: ladderDrawn[standing].fill,
    label: `${counts[standing]} ${ladderDrawn[standing].words.toLowerCase()}`,
  }));
  return { ...base, segments };
}

/** An approach: a row with a mark for each control behind it, held ones first, flagged when it holds none. */
function row(item: Source["approaches"][number], step: number): LadderNode {
  const { node: base, held, controls } = node(item, item[3], step);
  const marks: LadderMark[] = ladderStandings.flatMap((standing) =>
    controls
      .filter((control) => standingAt(control, step) === standing)
      .map((control) => ({
        key: source.controls[control]?.[0] ?? String(control),
        label: `${source.controls[control]?.[0]} ${source.controls[control]?.[1]}`,
        description: ladderDrawn[standing].words,
        tone: ladderDrawn[standing].tone,
        fill: ladderDrawn[standing].fill,
      })),
  );
  return { ...base, marks, ...(held === 0 ? { flagged: true } : {}) };
}

/** The ladder after a step of the stack: 0 is the reference baseline, the last the program's baseline. */
export function ladderAt(step: number): LadderLevel[] {
  return [
    { id: "goals", label: "Goals", nodes: source.goals.map((item) => card(item, step)) },
    {
      id: "objectives",
      label: "Objectives",
      nodes: source.objectives.map((item) => card(item, step)),
    },
    {
      id: "techniques",
      label: "Techniques",
      nodes: source.techniques.map((item) => card(item, step)),
    },
    {
      id: "approaches",
      label: "Approaches",
      layout: "rows",
      nodes: source.approaches.map((item) => row(item, step)),
    },
  ];
}

